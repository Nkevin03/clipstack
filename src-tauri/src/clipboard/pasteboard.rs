//! Thin, safe wrapper around `NSPasteboard.generalPasteboard`.

use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardType, NSPasteboardTypeFileURL, NSPasteboardTypeHTML,
    NSPasteboardTypePNG, NSPasteboardTypeRTF, NSPasteboardTypeString, NSPasteboardTypeTIFF,
    NSPasteboardTypeURL, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};

pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
const JPEG: &str = "public.jpeg";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ImageFormat {
    Png,
    Tiff,
    Jpeg,
}

impl ImageFormat {
    pub fn ext(self) -> &'static str {
        match self {
            ImageFormat::Png => "png",
            ImageFormat::Tiff => "tiff",
            ImageFormat::Jpeg => "jpg",
        }
    }
    pub fn from_ext(ext: &str) -> Option<Self> {
        match ext.to_ascii_lowercase().as_str() {
            "png" => Some(ImageFormat::Png),
            "tif" | "tiff" => Some(ImageFormat::Tiff),
            "jpg" | "jpeg" => Some(ImageFormat::Jpeg),
            _ => None,
        }
    }
}

/// Everything useful we could read from the pasteboard at a given change count.
#[derive(Default, Debug)]
pub struct Snapshot {
    pub types: Vec<String>,
    pub text: Option<String>,
    pub rtf: Option<Vec<u8>>,
    pub html: Option<String>,
    pub url: Option<String>,
    pub image: Option<(Vec<u8>, ImageFormat)>,
    pub files: Vec<String>,
}

impl Snapshot {
    pub fn has_type(&self, t: &str) -> bool {
        self.types.iter().any(|x| x == t)
    }
}

fn general() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

pub fn change_count() -> isize {
    autoreleasepool(|_| general().changeCount())
}

fn ty(s: &str) -> Retained<NSPasteboardType> {
    NSString::from_str(s)
}

/// Read the pasteboard. `max_image_bytes` caps image payloads (bigger images are skipped).
pub fn read(max_image_bytes: usize) -> Snapshot {
    autoreleasepool(|_| {
        let pb = general();
        let mut snap = Snapshot::default();
        if let Some(types) = pb.types() {
            snap.types = types.iter().map(|t| t.to_string()).collect();
        }
        // Never touch the payload of concealed/transient content.
        if snap.has_type(CONCEALED) || snap.has_type(TRANSIENT) {
            return snap;
        }
        unsafe {
            if snap.has_type(&NSPasteboardTypeFileURL.to_string()) {
                if let Some(items) = pb.pasteboardItems() {
                    for item in items.iter() {
                        if let Some(s) = item.stringForType(NSPasteboardTypeFileURL) {
                            if let Ok(u) = url::Url::parse(&s.to_string()) {
                                if let Ok(p) = u.to_file_path() {
                                    snap.files.push(p.to_string_lossy().into_owned());
                                }
                            }
                        }
                    }
                }
            }
            snap.text = pb
                .stringForType(NSPasteboardTypeString)
                .map(|s| s.to_string());
            if let Some(d) = pb.dataForType(NSPasteboardTypeRTF) {
                snap.rtf = Some(d.to_vec());
            }
            snap.html = pb
                .stringForType(NSPasteboardTypeHTML)
                .map(|s| s.to_string());
            snap.url = pb.stringForType(NSPasteboardTypeURL).map(|s| s.to_string());
            if snap.files.is_empty() {
                let candidates: [(&NSPasteboardType, ImageFormat); 3] = [
                    (NSPasteboardTypePNG, ImageFormat::Png),
                    (&ty(JPEG), ImageFormat::Jpeg),
                    (NSPasteboardTypeTIFF, ImageFormat::Tiff),
                ];
                for (t, fmt) in candidates {
                    if snap.has_type(&t.to_string()) {
                        if let Some(d) = pb.dataForType(t) {
                            if d.length() <= max_image_bytes {
                                snap.image = Some((d.to_vec(), fmt));
                            }
                        }
                        break;
                    }
                }
            }
        }
        snap
    })
}

/// What to put on the pasteboard when pasting an item.
#[derive(Default, Debug, Clone)]
pub struct WriteData {
    pub text: Option<String>,
    pub rtf: Option<Vec<u8>>,
    pub html: Option<String>,
    pub image: Option<(Vec<u8>, ImageFormat)>,
    pub files: Vec<String>,
}

/// Replace the pasteboard contents. Returns the resulting change count.
pub fn write(data: &WriteData) -> isize {
    autoreleasepool(|_| unsafe {
        let pb = general();
        pb.clearContents();
        if !data.files.is_empty() {
            let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = data
                .files
                .iter()
                .map(|p| {
                    ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(p)))
                })
                .collect();
            let arr = NSArray::from_retained_slice(&urls);
            pb.writeObjects(&arr);
        }
        if let Some((bytes, fmt)) = &data.image {
            let d = NSData::with_bytes(bytes);
            let t: Retained<NSPasteboardType> = match fmt {
                ImageFormat::Png => ty("public.png"),
                ImageFormat::Tiff => ty("public.tiff"),
                ImageFormat::Jpeg => ty(JPEG),
            };
            pb.setData_forType(Some(&d), &t);
        }
        if let Some(rtf) = &data.rtf {
            pb.setData_forType(Some(&NSData::with_bytes(rtf)), NSPasteboardTypeRTF);
        }
        if let Some(html) = &data.html {
            pb.setString_forType(&NSString::from_str(html), NSPasteboardTypeHTML);
        }
        if let Some(text) = &data.text {
            pb.setString_forType(&NSString::from_str(text), NSPasteboardTypeString);
        }
        pb.changeCount()
    })
}
